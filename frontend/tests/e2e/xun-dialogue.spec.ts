import {expect,test} from '@playwright/test'
import fs from 'node:fs/promises'
test('real Xun handles forgotten details, remembers the card and chooses tools conversationally',async({page})=>{
 test.skip(process.env.CAMPUSTRACE_REAL_LOCAL_AI!=='1','Requires local models')
 test.setTimeout(300_000)
 await page.goto('/login?redirect=/home')
 await page.getByLabel('用户名',{exact:true}).fill('student_01')
 await page.getByLabel('密码',{exact:true}).fill('CampusTrace!2026')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await page.locator('.agent-character').click()
 const audit:any[]=[];let writes=0
 page.on('request',r=>{if(r.url().includes('/assistant/agent/actions/')&&r.method()==='POST')writes++})
 async function say(text:string){
  const response=page.waitForResponse(r=>r.url().endsWith('/assistant/conversation/')&&r.request().method()==='POST',{timeout:100_000})
  await page.getByLabel('告诉小寻你记得的情况').fill(text)
  await page.getByRole('button',{name:'发送 ↑'}).click()
  const r=await response;const body=await r.json();expect(r.status(),JSON.stringify(body.error)).toBe(200)
  const d=body.data;expect(d.context_token).toBeTruthy()
  audit.push({user:text,reply:d.reply,intent:d.intent,question_field:d.question_field,unavailable:d.unavailable_fields,description:d.description,tools:d.tool_trace})
  await fs.writeFile('../artifacts/xun-dialogue-real-audit.json',JSON.stringify(audit,null,2))
  await expect(page.locator('.chat-thinking')).toHaveCount(0)
  return d
 }
 const first=await say('我昨天丢失了我的学生卡')
 const second=await say('我不知道在哪里丢的')
 expect(second.reply).not.toBe(first.reply)
 expect(second.unavailable_fields).toContain('location')
 expect(second.reply).not.toMatch(/你.{0,6}(?:还记得|知道).{0,8}(?:丢在哪|丢在了哪)/)
 expect(second.description).toMatch(/学生卡|校园卡/)
 await say('卡套的颜色我也不记得了，就是普通学校学生卡')
 const searched=await say('那先按我记得的信息帮我找找吧')
 expect(searched.tool_trace.some((t:any)=>/public_items/.test(t.tool))).toBe(true)
 expect(searched.candidates.length).toBeLessThanOrEqual(5)
 const help=await say('我有点着急，你能帮我做什么？没有照片也可以发布吗？')
 expect(help.reply).toMatch(/可以|纯文字|文字|照片/)
 expect(help.tool_trace.some((t:any)=>/public_items/.test(t.tool))).toBe(false)
 const publication=await say('那帮我整理一份寻物启事吧')
 expect(publication.ui_action?.type).toBe('publish')
 await expect(page.locator('.agent-publication')).toBeVisible()
 await expect(page.getByLabel('标题',{exact:true})).toHaveValue(/学生卡|校园卡/)
 expect(writes).toBe(0)
 await fs.writeFile('../artifacts/xun-dialogue-real-audit.json',JSON.stringify(audit,null,2))
 await page.screenshot({path:'../artifacts/xun-dialogue-real.png',fullPage:true})
})

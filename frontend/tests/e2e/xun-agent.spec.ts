import { expect, test } from '@playwright/test'

for (const width of [390, 1440]) {
  test(`full-body agent and accessible chat at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 960 })
    await page.goto('/home')
    await expect(page.locator('.agent-character .xun-agent').first()).toBeVisible()
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: `../artifacts/xun-agent-home-${width}.png`, fullPage: true })
    await page.locator('.agent-character').click()
    await expect(page.getByRole('dialog', { name: '和小寻一起找' })).toBeVisible()
    await expect(page.getByRole('link', { name: '登录后和小寻交流' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await page.screenshot({ path: `../artifacts/xun-agent-guest-${width}.png`, fullPage: true })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.locator('.agent-character')).toBeFocused()
  })
}

test('real local agent retrieves candidates inside chat without redirecting to forms', async ({ page }) => {
  test.skip(process.env.CAMPUSTRACE_REAL_LOCAL_AI !== '1', 'Requires local models')
  test.setTimeout(240_000)
  await page.goto('/login?redirect=/home')
  await page.getByLabel('用户名', { exact: true }).fill('student_01')
  await page.getByLabel('密码', { exact: true }).fill('CampusTrace!2026')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/home$/)
  await page.locator('.agent-character').click()
  await page.getByLabel('告诉小寻你记得的情况').fill('我丢了黑色华为耳机，充电盒盖有一道划痕，可能在图书馆，时间记不清。')
  const chatResponse = page.waitForResponse(response => response.url().endsWith('/assistant/conversation/') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '发送 ↑' }).click()
  const response = await chatResponse
  expect(response.status()).toBe(200)
  const body = await response.json()
  expect(body.data.provider.simulated).toBe(false)
  await expect(page.locator('.agent-candidate').first()).toBeVisible({ timeout: 80_000 })
  await expect(page.getByLabel('描述物品特征')).toHaveValue(/黑色华为耳机/)
  await page.getByLabel('告诉小寻你记得的情况').fill('补充一下，耳机没有挂件，也没有贴纸，其他细节不确定。')
  await page.getByRole('button', { name: '发送 ↑' }).click()
  await expect(page.locator('.chat-thinking')).toHaveCount(0, { timeout: 80_000 })
  await expect(page.getByLabel('描述物品特征')).toHaveValue(/没有挂件/)
  await page.screenshot({ path: '../artifacts/xun-agent-real-chat.png', fullPage: true })
  await expect(page).toHaveURL(/\/home$/)
  await expect(page.locator('.agent-candidate').first()).toContainText('耳机')
  await page.locator('.agent-candidate').first().getByRole('button',{name:'查看并核对这件物品'}).click()
  await expect(page.locator('.agent-selected')).toBeVisible()
  await expect(page.getByRole('dialog')).toBeVisible()
})

test('notebook details and acknowledgement do not trigger repeated confirmation',async({page})=>{
  test.skip(process.env.CAMPUSTRACE_REAL_LOCAL_AI!=='1','Requires local models')
  test.setTimeout(180_000)
  await page.goto('/login?redirect=/home')
  await page.getByLabel('用户名',{exact:true}).fill('student_01')
  await page.getByLabel('密码',{exact:true}).fill('CampusTrace!2026')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.locator('.agent-character').click()
  await page.getByLabel('告诉小寻你记得的情况').fill('我丢了一本本子，粉色的，A4大小，比较新。')
  await page.getByRole('button',{name:'发送 ↑'}).click()
  await expect(page.locator('.agent-tool-status')).toContainText('已检索真实线索',{timeout:90_000})
  await page.getByLabel('告诉小寻你记得的情况').fill('对哦')
  await page.getByRole('button',{name:'发送 ↑'}).click()
  await expect(page.locator('.chat-thinking')).toHaveCount(0,{timeout:90_000})
  await expect(page.getByLabel('描述物品特征')).not.toHaveValue(/对哦/)
  await expect(page.locator('.chat-turn.assistant').last()).not.toContainText('对吗')
  await expect(page.locator('.agent-tool-status')).toContainText('已检索真实线索')
  await page.screenshot({path:'../artifacts/xun-agent-notebook-tools.png',fullPage:true})
})

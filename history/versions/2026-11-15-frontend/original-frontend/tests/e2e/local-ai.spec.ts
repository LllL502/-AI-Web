import { expect, test } from '@playwright/test'
import path from 'node:path'

test('real local photo understanding and semantic retrieval', async ({ page }) => {
  test.skip(process.env.CAMPUSTRACE_REAL_LOCAL_AI !== '1', 'Requires downloaded local models and running demo services')
  test.setTimeout(240_000)
  await page.goto('/login?redirect=/assistant')
  await page.getByLabel('用户名', { exact: true }).fill('student_01')
  await page.getByLabel('密码', { exact: true }).fill('CampusTrace!2026')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/assistant/)
  await page.locator('input[type="file"]').setInputFiles(path.resolve('../data/demo-images/black-earbuds.png'))
  await page.getByRole('button', { name: '理解图片', exact: true }).click()
  const observation = page.locator('.follow-ups textarea')
  await expect(observation).toBeVisible({ timeout: 95_000 })
  await expect(observation).toHaveValue(/耳机/)
  await page.getByRole('button', { name: '确认并加入描述', exact: true }).click()
  await page.getByRole('button', { name: '提取待确认字段', exact: true }).click()
  await expect(page.locator('.confirmation-panel')).toBeVisible({ timeout: 120_000 })
  await page.getByRole('button', { name: '我已确认，检索真实公开候选', exact: true }).click()
  await expect(page.locator('.candidate-card').first()).toBeVisible({ timeout: 120_000 })
  await expect(page.locator('.candidate-card').first()).toContainText('黑色')
  await page.locator('.candidate-card').first().locator('.ranking-evidence summary').click()
  await expect(page.locator('.candidate-card').first().locator('.ranking-evidence')).toContainText('排序分')
  await expect(page.locator('.results-section')).toContainText('本地向量语义检索')
  await expect(page.locator('.mode-banner')).toHaveCount(0)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: '../artifacts/local-ai-browser-demo.png', fullPage: true })
})
